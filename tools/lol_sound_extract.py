"""Extract each champion's base-skin spell sounds: event names come from the champion data bins (Play_sfx_* strings), hashed (FNV-1)
and matched to the events bank; their wems are decoded with vgmstream-cli into nothing_mod/Content/LoL/Sounds/<Alias>_<slot>_<kind>.ogg.
Writes Content/LoL/LolSoundData.cs (alias -> slot -> cast/hit sound names).
Usage: .venv/bin/python lol_sound_extract.py [Alias ...]"""
import json, os, re, subprocess, sys, tempfile
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import lol_bnk as B

HERE = os.path.dirname(os.path.abspath(__file__))
EXT = '/Volumes/T7 Shield/league_of_legends_cilent/extracted/champions'
OUT = os.path.join(HERE, '..', 'nothing_mod/Content/LoL/Sounds')
SPELLS = json.load(open(os.path.join(HERE, 'spell_data/spells.json')))
# ordered by preference: earlier patterns win
CAST = ['oncast$', '_cast', 'windup', 'onmissilelaunch', 'missilelaunch', 'onmissilecast', 'onbuffactivate', 'buffactivate', 'start', 'activate', 'swing', 'launch', 'fire', 'loop']
HIT = ['onhit$', '_hit', 'impact', 'explode', 'detonate', 'land', 'damage', 'onbuffactivate', 'buffactivate']

def strings(alias):
    names = set()
    root = f'{EXT}/{alias}/data'
    for dp, _, fs in os.walk(root):
        for f in fs:
            if not f.endswith('.bin'): continue
            for m in re.finditer(rb'Play_sfx_[A-Za-z0-9_]+', open(os.path.join(dp, f), 'rb').read()):
                names.add(m.group().decode())
    return names

def decode(wem, ogg):
    wav = ogg[:-4] + '.tmp.wav'
    r = subprocess.run(['vgmstream-cli', '-o', wav, wem], capture_output=True)
    if r.returncode != 0 or not os.path.exists(wav): return False
    # mono, first 2.5 s, Vorbis: keeps the whole sound bank around 20 MB
    r = subprocess.run(['ffmpeg', '-y', '-v', 'error', '-i', wav, '-t', '2.5', '-ac', '1', '-c:a', 'libvorbis', '-q:a', '3', ogg], capture_output=True)
    os.remove(wav)
    return r.returncode == 0 and os.path.exists(ogg)

def do(alias):
    a = alias.lower()
    base = f'{EXT}/{alias}/assets/sounds/wwise2016/sfx/characters/{a}/skins/base/{a}_base_sfx_'
    if not os.path.exists(base + 'events.bnk'): return None
    ev = B.parse(base + 'events.bnk'); au = B.parse(base + 'audio.bnk')
    ev['didx'] = au['didx']  # sound objects live in the events bank, their wems in the audio bank
    evids = {k for k, (t, _) in ev['hirc'].items() if t == 4}
    names = {B.fnv1_32(n): n for n in strings(alias) if 'Skin' not in n}
    res = {}
    for slot, sp in zip('QWER', SPELLS[alias]):
        script = sp['n'] if sp else alias + slot
        key = script if script else alias + slot
        for kind, pats in (('cast', CAST), ('hit', HIT)):
            # event name = Play_sfx_<Alias>_<Spell...>_<Event>; the spell part may extend the script name (AhriQMissile, LuxLightBindingMis ...)
            rx = re.compile(r'^Play_sfx_' + re.escape(alias) + r'_' + re.escape(key) + r'|^Play_sfx_' + re.escape(alias) + r'_' + re.escape(alias) + slot + r'(?![a-z])', re.I)
            cands = [n for h, n in names.items() if h in evids and rx.search(n) and not re.search(r'basicattack|critattack', n, re.I)]
            picked = None
            for pat in pats:
                for n in sorted(cands, key=len):
                    if re.search(pat, n, re.I) and not (kind == 'cast' and re.search(r'(_hit$|onhit$|damage)', n, re.I)):
                        wems = [w for w in B.event_sounds(ev, B.fnv1_32(n)) if w in au['didx']]
                        if wems: picked = (n, wems[0]); break
                if picked: break
            if picked:
                out = f'{alias}_{slot}_{kind}'
                tmp = tempfile.mktemp(suffix='.wem')
                open(tmp, 'wb').write(B.wem_bytes(au, picked[1]))
                os.makedirs(OUT, exist_ok=True)
                if decode(tmp, f'{OUT}/{out}.ogg'): res[f'{slot}_{kind}'] = out
                os.remove(tmp)
    return res

if __name__ == '__main__':
    al = sys.argv[1:] or sorted(SPELLS)
    data = {}
    for a in al:
        try: r = do(a)
        except Exception as e: print('FAIL', a, type(e).__name__, e); continue
        if r is not None: data[a] = r
        print(a, len(r or {}), flush=True)
    if not sys.argv[1:]:
        rows = ',\n'.join(f'\t\t["{a}"] = new[] {{ ' + ', '.join(f'"{k}"' for k in sorted(v)) + ' }' for a, v in data.items() if v)
        open(os.path.join(HERE, '..', 'nothing_mod/Content/LoL/LolSoundData.cs'), 'w').write('''// <auto-generated> by tools/lol_sound_extract.py. Do not edit. </auto-generated>
using System.Collections.Generic;

namespace nothing_mod.Content.LoL
{
	// Champion -> available spell sounds ("Q_cast", "E_hit", ...). Files: Content/LoL/Sounds/<Alias>_<slot>_<kind>.ogg
	public static class LolSoundData
	{
		public static readonly Dictionary<string, string[]> Sounds = new()
		{
''' + rows + '''
		};
	}
}
''')
