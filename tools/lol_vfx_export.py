"""Export Ahri VFX entries as horizontal frame sheets into nothing_mod/Content/LoL/Special/Ahri_vfx_<name>.png.
Rendered frames travel 'down' the image, so directional effects are rotated 90 deg CCW (tip -> +x).
Usage: .venv/bin/python lol_vfx_export.py"""
import os, sys
import numpy as np
from PIL import Image
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import lol_vfx, lol_vfx_render as R

HERE = os.path.dirname(os.path.abspath(__file__))
TEX = '/Volumes/T7 Shield/league_of_legends_cilent/extracted/champions/Ahri/assets/characters/ahri/skins/base/particles'
OUT = os.path.join(HERE, '..', 'nothing_mod/Content/LoL/Special')
# name -> (rito file, key, rotate directional, seconds)
JOBS = {'Q': ('base_vfx.rito', '0xb0eca8', True), 'Qret': ('base_vfx.rito', '0xcf977937', True),
        'W': ('base_vfx.rito', '0xe7625c82', False), 'E': ('multi2.rito', '0x9147aab4', True),
        'R': ('base_vfx.rito', '0x90cbd4a0', True), 'Ehit': ('multi2.rito', '0x7e073ef0', False),
        'Rhit': ('multi2.rito', '0x67d99e81', False)}
names = lol_vfx.load_names()
DATA = []
for n, (f, key, rot) in JOBS.items():
    ents = dict(lol_vfx.parse_text(open(os.path.join(HERE, 'vfx_data', f), errors='ignore').read().split('\n')))
    if key not in ents:
        print('missing', n, key); continue
    frames, skipped, ne = R.render_frames([lol_vfx.resolve(ents[key], names)], TEX)
    ims = [Image.fromarray(fr, 'RGBA') for fr in frames]
    if rot: ims = [i.rotate(90) for i in ims]
    a = np.max([np.asarray(i)[..., 3] for i in ims], axis=0)
    ys, xs = np.nonzero(a > 4)
    if len(xs) == 0: print('empty', n); continue
    h = int(max(abs(xs - 256).max(), abs(ys - 256).max())) + 2   # keep emitter origin centred
    h = min(h, 256); S = 2 * h
    ims = [im.crop((256 - h, 256 - h, 256 + h, 256 + h)) for im in ims]
    k = 1
    while S // k * len(ims) > 8000: k += 1   # keep sheet under the 8192px texture limit
    C = S // k
    if k > 1: ims = [im.resize((C, C), Image.LANCZOS) for im in ims]
    sheet = Image.new('RGBA', (C * len(ims), C))
    for i, im in enumerate(ims): sheet.paste(im, (i * C, 0))
    DATA.append(f'\t\t["{n}"] = new VfxSheet({C}, {len(ims)}, {float(k)}f),')
    sheet.save(os.path.join(OUT, f'Ahri_vfx_{n}.png'), optimize=True)
    print(n, 'frames', len(ims), 'cell', C, 'emitters', ne)

open(os.path.join(OUT, 'AhriVfxData.cs'), 'w').write('''// <auto-generated> by tools/lol_vfx_export.py. Do not edit. </auto-generated>
using System.Collections.Generic;

namespace nothing_mod.Content.LoL.Special
{
	// Horizontal sheet of League VFX frames: cell size (px), frame count, Scale = how much the cell was shrunk to fit the texture limit.
	public record VfxSheet(int Cell, int Frames, float Scale);

	public static class AhriVfxData
	{
		public static readonly Dictionary<string, VfxSheet> Sheets = new()
		{
''' + chr(10).join(DATA) + '''
		};
	}
}
''')
